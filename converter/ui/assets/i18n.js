  var CATALOGUES = { ja: ja, en: en, zh: zh };

  function pickInitialLanguage() {
    var stored = null;
    try { stored = window.localStorage.getItem("access-viewer-language"); }
    catch (error) { stored = null; }
    if (stored && CATALOGUES[stored]) { return stored; }
    var candidates = (navigator.languages || [navigator.language || "en"]);
    for (var i = 0; i < candidates.length; i++) {
      var tag = String(candidates[i] || "").toLowerCase();
      if (tag.indexOf("ja") === 0) { return "ja"; }
      if (tag.indexOf("zh") === 0) { return "zh"; }
      if (tag.indexOf("en") === 0) { return "en"; }
    }
    return "en";
  }

  window.__ACCESS_I18N__ = {
    languages: LANGUAGES,
    catalogues: CATALOGUES,
    pickInitialLanguage: pickInitialLanguage,
    remember: function (code) {
      try { window.localStorage.setItem("access-viewer-language", code); }
      catch (error) { /* private browsing, file:// origin: not worth failing over */ }
    }
  };
